using System.IO;
using System.Text;
using AwesomeAssertions;
using QuickER.CodeGen.CSharp;

namespace QuickER.Tests.CodeGen.CSharp;

/// <summary>
/// 生成コードの版の行・内容ハッシュの行（<see cref="GeneratedContentHash"/>）を検証するテストクラス。
/// </summary>
/// <remarks>
/// 検証対象: (1) 刻んだ直後は一致する、(2) 改行コード・BOM・インデント・改行位置・末尾カンマ（整形ツールの変更）では
/// 一致したまま、(3) トークンが変わる編集では一致しない、(4) メタ行はハッシュの対象外、
/// (5) ハッシュ行が無いファイルは判定しない、(6) 実フィクスチャ全体でも (1)〜(3) が成り立つ。
/// </remarks>
public sealed class GeneratedContentHashTests
{
    private const string Version = "0.2.0";

    /// <summary>ヘッダー・using・初期化子・引数リストを含む小さな生成コード（CRLF）</summary>
    private static readonly string Sample = string.Join(
        "\r\n",
        "// <auto-generated />",
        "#nullable enable",
        "",
        "using System;",
        "",
        "namespace Acme;",
        "",
        "public sealed class Order",
        "{",
        "    public string Name { get; set; } = \"a b\";",
        "",
        "    public static string[] Codes() => new[] { \"x\", \"y\" };",
        "",
        "    public static bool TryCreate(int value, out Order? result, out string error)",
        "    {",
        "        result = null;",
        "        error = \"\";",
        "        return value > 0;",
        "    }",
        "}",
        ""
    );

    [Fact(DisplayName = "刻印: auto-generated 行の直後へ版の行と内容ハッシュの行を差し込む")]
    public void Stamp_InsertsVersionAndHashLinesAfterAutoGeneratedLine()
    {
        var stamped = GeneratedContentHash.Stamp(Sample, Version);
        var lines = stamped.Split("\r\n");

        lines[0].Should().Be("// <auto-generated />");
        lines[1].Should().Be("// Generated by QuickER 0.2.0");
        lines[2].Should().MatchRegex("^// Content hash: sha256:[0-9a-f]{64}$");
        lines[3].Should().Be("#nullable enable");
        // メタ行を除けば元の本文そのまま
        string.Join("\r\n", lines.Take(1).Concat(lines.Skip(3))).Should().Be(Sample);
    }

    [Fact(DisplayName = "刻印: LF の本文には LF で差し込む")]
    public void Stamp_KeepsLfNewLinesWhenContentUsesLf()
    {
        var stamped = GeneratedContentHash.Stamp(Sample.Replace("\r\n", "\n"), Version);

        stamped.Should().NotContain("\r");
        GeneratedContentHash.Verify(stamped).Should().Be(GeneratedContentHashStatus.Unchanged);
    }

    [Fact(DisplayName = "刻印: auto-generated 行で始まらない本文は拒否する")]
    public void Stamp_RejectsContentWithoutAutoGeneratedHeader()
    {
        var act = () => GeneratedContentHash.Stamp("namespace Acme;", Version);

        act.Should().Throw<ArgumentException>();
    }

    [Fact(DisplayName = "照合: 刻んだ直後は一致する")]
    public void Verify_FreshlyStamped_IsUnchanged()
    {
        var stamped = GeneratedContentHash.Stamp(Sample, Version);

        GeneratedContentHash.Verify(stamped).Should().Be(GeneratedContentHashStatus.Unchanged);
    }

    [Fact(DisplayName = "照合: ハッシュ行が無ければ判定しない")]
    public void Verify_WithoutHashLine_IsNotStamped()
    {
        GeneratedContentHash.Verify(Sample).Should().Be(GeneratedContentHashStatus.NotStamped);
    }

    [Fact(DisplayName = "照合: 先頭のコメント塊より後ろのハッシュ行は刻印とみなさない")]
    public void Verify_HashLineBelowFirstCode_IsNotStamped()
    {
        // 先頭のコメント行の塊より後ろにある同じ文字列の行は、刻まれたハッシュとして扱わない
        var content =
            Sample + "// Content hash: sha256:" + GeneratedContentHash.Compute(Sample) + "\r\n";

        GeneratedContentHash.Verify(content).Should().Be(GeneratedContentHashStatus.NotStamped);
    }

    [Fact(
        DisplayName = "照合: 先頭のコメント塊に空行が挟まってもハッシュ行を見つけ、編集を検出する"
    )]
    public void Verify_BlankLineInsideHeader_StillFindsHashLine()
    {
        var stamped = GeneratedContentHash.Stamp(Sample, Version);

        // auto-generated 行とメタ行の間・メタ行どうしの間に空行（空白だけの行を含む）を挟む。
        // 空白だけの変更なので一致したまま、本文を変えれば不一致になる（判定不能へ倒れない）
        var withBlankLines = stamped
            .Replace("// <auto-generated />\r\n", "// <auto-generated />\r\n\r\n")
            .Replace("\r\n// Content hash:", "\r\n   \r\n// Content hash:");

        GeneratedContentHash
            .Verify(withBlankLines)
            .Should()
            .Be(GeneratedContentHashStatus.Unchanged);
        GeneratedContentHash
            .Verify(withBlankLines.Replace("value > 0", "value >= 0"))
            .Should()
            .Be(GeneratedContentHashStatus.Modified);
    }

    [Fact(DisplayName = "照合: 壊れたハッシュ行は不一致（安全側）")]
    public void Verify_MalformedHashLine_IsModified()
    {
        var stamped = GeneratedContentHash.Stamp(Sample, Version);
        var broken = System.Text.RegularExpressions.Regex.Replace(
            stamped,
            "sha256:[0-9a-f]{64}",
            "sha256:not-a-hash"
        );

        GeneratedContentHash.Verify(broken).Should().Be(GeneratedContentHashStatus.Modified);
    }

    [Fact(DisplayName = "照合: 版の行はハッシュの対象外")]
    public void Verify_DifferentVersionLine_IsUnchanged()
    {
        // 版の行はハッシュの対象外＝版の行だけを書き換えても一致する
        var stamped = GeneratedContentHash.Stamp(Sample, Version);

        GeneratedContentHash
            .Verify(stamped.Replace("QuickER 0.2.0", "QuickER 9.9.9"))
            .Should()
            .Be(GeneratedContentHashStatus.Unchanged);
    }

    public static TheoryData<string, Func<string, string>> FormattingChanges =>
        new()
        {
            { "CRLF → LF", s => s.Replace("\r\n", "\n") },
            { "CRLF → CR", s => s.Replace("\r\n", "\r") },
            { "BOM 付与", s => "\uFEFF" + s },
            { "インデントをタブへ", s => s.Replace("    ", "\t") },
            { "行末空白の付与", s => s.Replace("\r\n", "  \r\n") },
            {
                "引数リストの折り返し（CSharpier 相当）",
                s =>
                    s.Replace(
                        "TryCreate(int value, out Order? result, out string error)",
                        "TryCreate(\r\n        int value,\r\n        out Order? result,\r\n        out string error\r\n    )"
                    )
            },
            {
                "初期化子の折り返しと末尾カンマ（CSharpier 相当）",
                s =>
                    s.Replace(
                        "new[] { \"x\", \"y\" }",
                        "new[]\r\n    {\r\n        \"x\",\r\n        \"y\",\r\n    }"
                    )
            },
            {
                "空の本体の 1 行化（CSharpier 相当）",
                s => s.Replace("{\r\n        result = null;", "{ result = null;")
            },
        };

    [Theory(DisplayName = "照合: 整形だけの変更では一致したまま")]
    [MemberData(nameof(FormattingChanges))]
    public void Verify_FormattingOnlyChange_IsUnchanged(
        string description,
        Func<string, string> change
    )
    {
        var stamped = GeneratedContentHash.Stamp(Sample, Version);
        var changed = change(stamped);

        changed.Should().NotBe(stamped, description);
        GeneratedContentHash
            .Verify(changed)
            .Should()
            .Be(GeneratedContentHashStatus.Unchanged, description);
    }

    public static TheoryData<string, Func<string, string>> TokenChanges =>
        new()
        {
            { "リテラルの値", s => s.Replace("= \"a b\"", "= \"a c\"") },
            { "演算子", s => s.Replace("value > 0", "value >= 0") },
            { "メンバーの追加", s => s.Replace("}\r\n", "    public int Id;\r\n}\r\n") },
            { "コメントの追加", s => s.Replace("result = null;", "result = null; // edited") },
            { "閉じ括弧直前以外のカンマ除去", s => s.Replace("\"x\", \"y\"", "\"x\" \"y\"") },
        };

    [Theory(DisplayName = "照合: トークンが変わる編集は不一致")]
    [MemberData(nameof(TokenChanges))]
    public void Verify_TokenChange_IsModified(string description, Func<string, string> change)
    {
        var stamped = GeneratedContentHash.Stamp(Sample, Version);
        var changed = change(stamped);

        changed.Should().NotBe(stamped, description);
        GeneratedContentHash
            .Verify(changed)
            .Should()
            .Be(GeneratedContentHashStatus.Modified, description);
    }

    [Fact(DisplayName = "正規化: 空白と閉じ括弧直前のカンマだけを除く")]
    public void Normalize_RemovesWhitespaceAndTrailingCommasOnly()
    {
        GeneratedContentHash
            .Normalize("f( a ,\r\n b , ) ;\n[ 1, ]\t{ x = 1, }")
            .Should()
            .Be("f(a,b);[1]{x=1}");
    }

    [Fact(DisplayName = "実フィクスチャ: 整形では一致・1 トークンの編集で不一致")]
    public void RealFixture_SurvivesFormattingAndDetectsEdit()
    {
        // 実フィクスチャ全体（65 万文字級）でも、整形相当の変更では一致・1 トークンの変更では不一致になる
        var fixture = File.ReadAllText(
            ResolveRepoPath("tests/QuickER.Tests/GeneratedFixture/QueryFixture.g.cs")
        );
        var stamped = GeneratedContentHash.Stamp(StripMetaLines(fixture), Version);

        // 改行コード・インデントの変更に加え、既存の末尾カンマ（enum の最終メンバー等）を外す
        var withoutTrailingCommas = System.Text.RegularExpressions.Regex.Replace(
            stamped.Replace("\r\n", "\n").Replace("    ", "  "),
            @",(\s*\n\s*[}\])])",
            "$1"
        );
        withoutTrailingCommas.Length.Should().BeLessThan(stamped.Length);
        GeneratedContentHash
            .Verify(withoutTrailingCommas)
            .Should()
            .Be(GeneratedContentHashStatus.Unchanged);

        var edited = stamped.Replace("ThrowIfNull(", "ThrowIfNullOrEmpty(");
        edited.Should().NotBe(stamped);
        GeneratedContentHash.Verify(edited).Should().Be(GeneratedContentHashStatus.Modified);
    }

    /// <summary>フィクスチャがすでにメタ行を持っていても持っていなくても、刻む前の形へ戻す</summary>
    private static string StripMetaLines(string content)
    {
        var builder = new StringBuilder();

        foreach (var line in content.Split("\r\n"))
        {
            if (
                line.StartsWith(GeneratedContentHash.VersionLinePrefix, StringComparison.Ordinal)
                || line.StartsWith(GeneratedContentHash.HashLinePrefix, StringComparison.Ordinal)
            )
            {
                continue;
            }

            builder.Append(line).Append("\r\n");
        }

        return builder.ToString(0, builder.Length - 2);
    }

    /// <summary>テストアセンブリの位置から QuickER.slnx を目印にリポジトリ直下を遡り、相対パスを解決する</summary>
    private static string ResolveRepoPath(string relativePath)
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);

        while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "QuickER.slnx")))
        {
            dir = dir.Parent;
        }

        return Path.Combine(
            dir?.FullName ?? throw new DirectoryNotFoundException("QuickER.slnx not found."),
            relativePath
        );
    }
}
