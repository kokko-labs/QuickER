    /// <summary>名前が固定の名簿（ランタイム・固定の生成物・外部の型）のどれかに載っているか</summary>
    public static bool IsReserved(string name) =>
        Runtime.Contains(name) || FixedGenerated.Contains(name) || External.Contains(name);

    private static HashSet<string> Create(params string[] names) =>
        new(names, StringComparer.Ordinal);
